#pragma once
// Профілі батарейних пакетів.
//
// Цей файл — єдине місце, де описані типи акумуляторів. Щоб додати новий
// пакет, допишіть рядок у таблицю нижче; чіпати main.cpp не потрібно.
//
// Профіль вибирається автоматично, за кількістю комірок, яку повідомляє BMS
// у тезі 0x79. Так зроблено навмисно: пакети міняються фізично, і якби тип
// задавався константою, кожна заміна вимагала б перепрошивки пульта — а
// помилитися й лишити чужі пороги дуже легко.
//
// Пороги — це межі НОРМИ для хімії, а не уставки захисту BMS. Вихід за них
// піднімає код аварії 1 і червоний індикатор. Переплутати хімію дорого в
// обидва боки: з літій-залізними порогами справний NMC дає аварію на кожному
// кадрі (4.12 В > 3.65), а з NMC-порогами глибоко розряджений LiFePO4
// проходить як справний.
//
// Обмеження: кількість комірок має бути унікальною в таблиці. Два пакети з
// однаковим 7S, але різною хімією, автоматично не розрізнити — тоді типи
// доведеться розділяти якось інакше.

struct PackProfile {
  const char *name;  // Для логу, щоб було видно, який профіль підхопився
  uint8_t cells;     // Кількість комірок — за нею і впізнаємо пакет
  float cellMinV;    // Нижче — перерозряд
  float cellMaxV;    // Вище — перенапруга
};

static const PackProfile PACK_PROFILES[] = {
    {"LiFePO4 8S", 8, 2.60f, 3.65f},
    {"NMC 7S", 7, 2.80f, 4.25f},
};

static const uint8_t PACK_PROFILE_COUNT =
    sizeof(PACK_PROFILES) / sizeof(PACK_PROFILES[0]);
